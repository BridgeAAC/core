function repairImage<T extends { label: string; image?: string }>(item: T): boolean {
  const m = /^arasaac:(\d+)$/.exec(item.image ?? '');
  if (!m) return false;
  const pairs = LEGACY_IDS[item.label.trim().toLowerCase()];
  const hit = pairs?.find(([old]) => old === Number(m[1]));
  if (!hit) return false;
  if (hit[1]) item.image = `arasaac:${hit[1]}`;
  else delete item.image;
  return true;
}

export function repairLegacyArasaacPictures(vocab: Vocabulary): boolean {
  let changed = false;
  for (const page of vocab.pages) {
    for (const button of page.buttons as Button[]) {
      if (repairImage(button)) changed = true;
      for (const variant of Object.values(button.variants ?? {})) {
        if (variant.label && repairImage(variant as { label: string; image?: string })) changed = true;
      }
    }
  }
  return changed;
}
