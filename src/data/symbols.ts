export function symbolIdForWord(raw: string): string | undefined {
  const w = raw.trim().toLowerCase().replace(/[’‘]/g, "'").replace(/[?!.,…]+$/, '').replace(/\s+/g, ' ');
  if (!w) return undefined;
  if (Object.prototype.hasOwnProperty.call(SYMBOLS, w)) return w;
  const alias = SYMBOL_ALIASES[w];
  if (alias && Object.prototype.hasOwnProperty.call(SYMBOLS, alias)) return alias;
  return undefined;
}

export function getSymbolSvg(id: string): string | null {
  if (!Object.prototype.hasOwnProperty.call(SYMBOLS, id)) return null;
  return SYMBOLS[id]();
}
